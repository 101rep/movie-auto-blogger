def get_hook(category: str = None, product_name: str = "이 상품") -> str:
    """카테고리별 또는 랜덤으로 1초 도파민 훅을 반환합니다."""
    if category and category in HOOK_VAULT:
        templates = HOOK_VAULT[category]
    else:
        all_templates = [t for sublist in HOOK_VAULT.values() for t in sublist]
        templates = all_templates
    chosen = random.choice(templates)
    return chosen.replace("{product_name}", product_name)

def get_all_hooks_count() -> int:
    return sum(len(v) for v in HOOK_VAULT.values())
